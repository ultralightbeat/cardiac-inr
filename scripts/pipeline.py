"""The whole study for one patient with one command.

    python scripts/pipeline.py                                   # first patient under data/, standard preset
    python scripts/pipeline.py --patient data/acdc/patient020
    python scripts/pipeline.py --patient path/to/scan_4d.nii.gz  # any 4D NIfTI (3D heart needs ACDC labels)
    python scripts/pipeline.py --preset quick                    # 3-5 min check that everything runs
    python scripts/pipeline.py --preset full                     # the settings of the report, ~3 h on a laptop CPU

Steps (each writes its own folder under results/<patient>/experiments or /final):
  1. main      E1 hidden slices (SIREN, ReLU, interpolation) + E2 every second frame hidden,
               three time encodings (raw, scaled, periodic)
  2. stride4   E2 with only every 4th frame kept: SIREN vs ReLU of the same size vs interpolation
  3. blend     re-evaluation of step 2 with the fixed blend 0.5 SIREN + 0.5 interpolation
  4. heart4d   final field on ALL data (saved to models/<patient>/) -> 3D/4D heart, volumes, EF
At the end results/<patient>/SUMMARY.md collects all tables.

Approximate CPU time (Intel Core Ultra 5, no GPU): quick 5 min, standard 1 h, full 3 h.
"""

from __future__ import annotations

import argparse
import os
import subprocess
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "src"))

from inr4d.data import patients as P  # noqa: E402
from inr4d.data import sampling as S  # noqa: E402

PRESETS = {
    #            e1 steps, e2 steps, stride4 steps, final steps, width, extra
    "quick":    dict(e1=150, e2=150, s4=150, final=300, width=64, batch=4096),
    "standard": dict(e1=3000, e2=4000, s4=8000, final=10000, width=256, batch=16384),
    "full":     dict(e1=3000, e2=8000, s4=20000, final=20000, width=256, batch=16384),
}


def run(cmd):
    print("\n$ " + " ".join(cmd), flush=True)
    t = time.time()
    subprocess.run([sys.executable] + cmd, check=True)
    print(f"[{time.time() - t:.0f} s]")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--patient", default=None)
    ap.add_argument("--preset", choices=list(PRESETS), default="standard")
    ap.add_argument("--time-scale", type=float, default=0.1)
    ap.add_argument("--threads", type=int, default=None)
    ap.add_argument("--skip", nargs="*", default=[], choices=["main", "stride4", "blend", "heart4d"])
    a = ap.parse_args()

    patient = P.resolve_patient(a.patient)
    name = P.patient_name(patient)
    c = PRESETS[a.preset]
    tag = "" if a.preset != "quick" else "quick_"
    common = ["--patient", patient, "--time-scale", str(a.time_scale), "--width", str(c["width"]),
              "--batch", str(c["batch"])] + (["--threads", str(a.threads)] if a.threads else [])
    exp = os.path.join(HERE, "run_experiments.py")
    out = {"main": P.results_dir(patient, f"experiments/{tag}main"),
           "stride4": P.results_dir(patient, f"experiments/{tag}stride4"),
           "heart4d": P.results_dir(patient, f"final/{tag}heart4d")}
    t0 = time.time()

    if "main" not in a.skip:
        run([exp, "--exp", "e1", "e2", "--out", out["main"], "--steps-e1", str(c["e1"]),
             "--steps-e2", str(c["e2"]), "--encodings", "raw", "scaled", "periodic"] + common)
    if "stride4" not in a.skip:
        run([exp, "--exp", "e2", "--out", out["stride4"], "--frame-stride", "4", "--e2-models", "siren", "relu",
             "--encodings", "scaled", "--steps-e2", str(c["s4"])] + common)
    if "blend" not in a.skip:
        run([os.path.join(HERE, "evaluate_blend.py"), out["stride4"]])
    has_labels = bool(S.load_labels(P.patient_dir(patient)))
    if "heart4d" not in a.skip:
        if has_labels:
            mdir = os.path.join(P.model_dir(patient), "quick") if tag else P.model_dir(patient)
            run([os.path.join(HERE, "render_4d.py"), "--train", "--steps", str(c["final"]), "--out", out["heart4d"],
                 "--model-dir", mdir] + common)
        else:
            print("\nno expert labels (*_gt.nii) for this patient: skipping the 3D/4D heart step")

    # summary
    parts = [f"# {name}: summary ({a.preset} preset)", "",
             f"Generated by scripts/pipeline.py in {(time.time() - t0) / 60:.0f} min. "
             "PSNR in dB on data hidden from the network; 'heart' = inside the dilated expert labels.", ""]
    for title, path in (("Step 1. Hidden slices (E1) and every second frame hidden (E2)", os.path.join(out["main"], "results.md")),
                        ("Step 2. Only every 4th frame kept: SIREN vs ReLU", os.path.join(out["stride4"], "results.md")),
                        ("Step 3. Blend 0.5 SIREN + 0.5 interpolation", os.path.join(out["stride4"], "blend.md")),
                        ("Step 4. Final field on all data: chamber volumes and ejection fraction",
                         os.path.join(out["heart4d"], "summary.md"))):
        if os.path.exists(path):
            with open(path, encoding="utf-8") as f:
                body = [ln for ln in f.read().splitlines() if not ln.startswith("# ")]
            parts += [f"## {title}", ""] + body + [""]
    summary = os.path.join("results", name, f"{tag}SUMMARY.md")
    os.makedirs(os.path.dirname(summary), exist_ok=True)
    with open(summary, "w", encoding="utf-8") as f:
        f.write("\n".join(parts) + "\n")
    print(f"\nall done in {(time.time() - t0) / 60:.0f} min -> {summary}")


if __name__ == "__main__":
    main()
